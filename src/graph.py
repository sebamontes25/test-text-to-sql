builder.add_node("generate_sql_query_json", generate_sql_query_json)
builder.add_node("run_query", run_query)
builder.add_node("call_api_node", call_api_node)

builder.add_edge(START, "generate_sql_query_json")
builder.add_edge("generate_sql_query_json", "run_query")
builder.add_edge("run_query", "call_api_node")
builder.add_edge("call_api_node", END)

graph = builder.compile()
